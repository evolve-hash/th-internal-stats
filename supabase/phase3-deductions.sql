-- WHAT THIS DOES
--   1. Adds three optional columns to `transactions`:
--        referral_fee   — referral paid out on this sale
--        brokerage_fee  — the brokerage's split of this sale
--        other_costs    — TC fee, home warranty, and similar
--   2. Fills them in for the 403 historical sales where the
--      workbook breaks those numbers out (2015 onward).
--
-- WHY
--   So the "Where the Money Goes" panel is computed from the
--   sales themselves instead of from a frozen copy of the
--   spreadsheet. Once this runs, every sale you add or edit in
--   the dashboard moves that breakdown too.
--
-- SAFE TO RUN TWICE. It only adds columns that do not exist yet
-- and overwrites the three deduction columns on rows it matches
-- by year + client + gross commission. It never deletes a row and
-- never touches any other column.
--
-- HOW TO RUN
--   supabase.com -> your project -> SQL Editor -> New query
--   Paste this whole file, press Run. Takes a few seconds.
-- ============================================================

